CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255),
    account_type VARCHAR(10) NOT NULL DEFAULT 'USER',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_created_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_users_email_lower ON public.users (LOWER(email));
CREATE UNIQUE INDEX uq_users_email_normalized ON public.users (LOWER(email));

CREATE TABLE public.user_first_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES public.users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL,
    purpose VARCHAR(20) NOT NULL DEFAULT 'FIRST_ACCESS',
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    password_created_at TIMESTAMP WITH TIME ZONE
);
